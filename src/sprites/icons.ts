export type IconName = keyof typeof ICONS;
export const ICON_NAMES = Object.keys(ICONS) as IconName[];

export function iconRaster(name: IconName, color: string, accent = '#ffc63d'): Raster {
  const art = ICONS[name];
  return rasterize(12, 12, [{ art }], { x: color, a: accent });
}

export const ALL_ICON_ART: Record<string, Art> = Object.fromEntries(
  Object.entries(ICONS).map(([k, v]) => [`icon.${k}`, v]),
);
